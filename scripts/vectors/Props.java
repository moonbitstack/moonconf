// Generate the properties vectors with `java.util.Properties` itself.
//
// Reading: every case is loaded by a real `Properties` and the pairs it ends up
// with become assertions. Writing: every pair is stored by a real `Properties`
// and the line it produces becomes the expected output of `props.dumps`, which is
// the only way to be sure an escape is the escape Java writes.
//
// Run from the repository root: java scripts/vectors/Props.java
// (the file is named with a capital so that the single-file launcher finds the
// class inside it)

import java.io.StringReader;
import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;

public class Props {
    static final List<String[]> READ_CASES = new ArrayList<>();
    static final List<String[]> WRITE_CASES = new ArrayList<>();

    static void read(String label, String text) {
        READ_CASES.add(new String[] {label, text});
    }

    static void write(String key, String value) {
        WRITE_CASES.add(new String[] {key, value});
    }

    public static void main(String[] args) throws Exception {
        read("plain", "a=b\n");
        read("colon separator", "a:b\n");
        read("whitespace separator", "a b\n");
        read("spaces around", "  a  =  b  \n");
        read("value with equals", "a=b=c\n");
        read("escaped separator in key", "a\\=b=c\n");
        read("comment", "# a note\na=1\n");
        read("bang comment", "! another\na=1\n");
        read("continuation", "a=one\\\n    two\n");
        read("continuation no separator", "a=one\\\ntwo\n");
        read("unicode escape", "a=\\u4f60\\u597d\n");
        read("escaped space in key", "a\\ b=c\n");
        read("empty value", "a=\n");
        read("key only", "a\n");
        read("duplicate", "a=1\na=2\n");
        read("trailing spaces kept", "a=b   \n");
        read("trailing backslash", "a=b\\\\\n");
        read("unknown escape", "a=\\q\n");
        read("crlf lines", "a=1\r\nb=2\r\n");
        read("colon then equals", "a:=b\n");
        read("tab separator", "a\tb\n");
        read("escaped unicode in key", "\\u4f60=1\n");
        read("blank lines", "\n\na=1\n\n");

        write("a", "b");
        write("a b", "c");
        write("a=b", "c");
        write("a:b", "c");
        write("a#b", "c!");
        write("a", " leading");
        write("a", "line\nbreak");
        write("a", "tab\there");
        write("a", "unicode \u4f60\u597d");
        write("a", "back\\slash");
        write("key ", "v");
        write("a", "trail ");

        StringBuilder out = new StringBuilder();
        out.append("// Copyright 2026 Leo Cheng\n");
        out.append("// SPDX-License-Identifier: Apache-2.0\n\n");
        out.append("// Generated by scripts/vectors/Props.java from `java.util.Properties`.\n");
        out.append("// Do not edit by hand: the answers below are what that class produced.\n\n");

        for (String[] item : READ_CASES) {
            String label = item[0];
            String text = item[1];
            Properties properties = new Properties();
            String failure = null;
            try {
                properties.load(new StringReader(text));
            } catch (Exception error) {
                failure = error.getClass().getSimpleName();
            }
            out.append("///|\n");
            out.append("test \"java: ").append(label.replace("\"", "\\\"")).append("\" {\n");
            if (failure != null) {
                out.append("  let refused = try Ok(@props.parse(\"").append(literal(text)).append("\"))");
                out.append(" catch { error => Err(error) }\n");
                out.append("  match refused {\n    Err(_) => ()\n");
                out.append("    Ok(_) => fail(\"").append(failure).append(" should be refused\")\n  }\n}\n\n");
                continue;
            }
            out.append("  let doc = @props.parse(\"").append(literal(text)).append("\")\n");
            List<String> keys = new ArrayList<>(properties.stringPropertyNames());
            keys.sort(String::compareTo);
            for (String key : keys) {
                out.append("  assert_eq(doc.get(\"").append(literal(key)).append("\"), Some(\"");
                out.append(literal(properties.getProperty(key))).append("\"))\n");
            }
            out.append("}\n\n");
        }

        for (String[] item : WRITE_CASES) {
            String key = item[0];
            String value = item[1];
            Properties properties = new Properties();
            properties.setProperty(key, value);
            // `store(OutputStream)` is the flavour that escapes what ISO-8859-1
            // cannot carry, which is the contract this writer promises.
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            properties.store(bytes, null);
            String stored = bytes.toString(StandardCharsets.ISO_8859_1);
            String line = null;
            for (String candidate : stored.split("\r?\n")) {
                if (!candidate.startsWith("#")) {
                    line = candidate;
                    break;
                }
            }
            out.append("///|\n");
            out.append("test \"java store: ").append(literal(key)).append(" = ").append(literal(value)).append("\" {\n");
            out.append("  let doc = @props.Doc::new([@props.Pair::new(\"").append(literal(key));
            out.append("\", \"").append(literal(value)).append("\")])\n");
            out.append("  assert_eq(@props.dumps(doc), \"").append(literal(line)).append("\\n\")\n");
            out.append("}\n\n");
        }

        Path target = Path.of("src", "props", "vectors_test.mbt");
        Files.writeString(target, out.toString(), StandardCharsets.UTF_8);
        System.out.println("wrote " + target + " (" + READ_CASES.size() + " read, " + WRITE_CASES.size() + " write)");
    }

    /** A string as a MoonBit literal body: no quotes of its own. */
    static String literal(String text) {
        StringBuilder out = new StringBuilder();
        for (char c : text.toCharArray()) {
            switch (c) {
                case '\\' -> out.append("\\\\");
                case '"' -> out.append("\\\"");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> out.append(c);
            }
        }
        return out.toString();
    }
}
