#!/usr/bin/env python3
"""Generate the `.env` vectors from `python-dotenv`.

Every case is read by the installed `python-dotenv` -- with interpolation on and
off -- and the values it produces become a MoonBit test. A case it cannot read at
all is asserted to be refused here too.

The environment is cleared while the cases are read, so a value like `${PATH}` in
a case cannot pick up this machine's environment and bake it into a test.

Run from the repository root:
    python scripts/vectors/envfile.py
"""

import os
from io import StringIO

from dotenv.main import DotEnv

CASES = [
    ("bare", "A=1\n"),
    ("spaces around", "A = 1\n"),
    ("spaces before name", "  A=1\n"),
    ("empty value", "A=\n"),
    ("empty with comment", "A= # nothing\n"),
    ("name alone", "A\n"),
    ("name alone with export", "export A\n"),
    ("comment line", "# A=1\nB=2\n"),
    ("indented comment", "   # A=1\nB=2\n"),
    ("export", "export A=1\n"),
    ("export tab", "export\tA=1\n"),
    ("export two spaces", "export   A=1\n"),
    ("hash in value", "A=a#b\n"),
    ("hash after spaces", "A=a # b\n"),
    ("comment after quoted", 'A="a" # note\n'),
    ("single quotes", "A='a b'\n"),
    ("single quote escape", "A='it\\'s'\n"),
    ("single quote backslash", "A='a\\\\b'\n"),
    ("single quote other escape", "A='a\\nb'\n"),
    ("single quoted reference", "A='${B}'\nB=x\n"),
    ("double quotes", 'A="a b"\n'),
    ("double quote escapes", 'A="a\\nb\\tc"\n'),
    ("double quote escaped dollar", 'A="\\${B}"\nB=x\n'),
    ("double quote backslash", 'A="a\\\\b"\n'),
    ("double quote unknown escape", 'A="a\\qb"\n'),
    ("double quote single quote", 'A="it\\\'s"\n'),
    ("quoted key", "'A B'=1\n"),
    ("multiline double", 'A="one\ntwo"\n'),
    ("multiline single", "A='one\ntwo'\n"),
    ("reference above", "B=x\nA=${B}-y\n"),
    ("bare dollar name", "B=x\nA=$B-y\n"),
    ("reference below is empty", "A=${B}-y\nB=x\n"),
    ("reference default", "A=${B:-fallback}\n"),
    ("reference default with value", "B=x\nA=${B:-fallback}\n"),
    ("unclosed reference", "A=${B\n"),
    ("reference with colon", "A=${B:fallback}\n"),
    ("empty reference", "A=${}\n"),
    ("self reference", "P=/usr/bin\nP=${P}:/opt/bin\n"),
    ("later wins", "A=1\nA=2\n"),
    ("blank lines", "\n\nA=1\n\n\n"),
    ("crlf", "A=1\r\nB=2\r\n"),
    ("cr only", "A=1\rB=2\r"),
    ("no trailing newline", "A=1"),
    ("bom", "\ufeffA=1\n"),
    ("equals in value", "A=b=c\n"),
    ("path value", "P=/opt/a:/opt/b\n"),
    ("unicode value", "A=h\u00e9llo\n"),
    ("unicode name", "A\u00e9=1\n"),
    ("quoted empty", 'A=""\n'),
    ("quoted hash", 'A="#not a comment"\n'),
    ("junk after quoted", 'A="x" trailing\n'),
    ("name and value without sign", "A b\n"),
    ("unclosed double quote", 'A="x\n'),
    ("unclosed single quote", "A='x\n"),
    ("dollar alone", "A=cost: $\n"),
    ("dollar before space", "A=cost: $ B\n"),
    ("two names on a line", "A=1 B=2\n"),
]

VERBATIM_CASES = ["A=1\n", "B=x\nA=${B}\n", "A='${B}'\nB=x\n"]


def read(text, interpolate):
    saved = dict(os.environ)
    os.environ.clear()
    try:
        values = DotEnv(
            dotenv_path=None, stream=StringIO(text), interpolate=interpolate
        ).dict()
        # A second reader: `dict()` and `parse()` both consume the stream.
        # `Doc::keys` names each variable once, keeping the first place it was
        # written, so the reference list is deduplicated the same way.
        keys = list(
            dict.fromkeys(
                key for key, _ in DotEnv(dotenv_path=None, stream=StringIO(text)).parse()
            )
        )
        return values, keys
    finally:
        os.environ.update(saved)


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\ufeff":
            out.append("\\u{FEFF}")
        else:
            out.append(ch)
    return "".join(out)


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    target = os.path.join(root, "src", "dotenv", "vectors_test.mbt")
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/vectors/envfile.py from `python-dotenv`.",
        "// Do not edit by hand: the answers below are what that reader produced.",
        "",
    ]
    for label, text in CASES:
        try:
            values, keys = read(text, True)
        except Exception as error:
            lines.append("///|")
            lines.append(f'test "python-dotenv: {label}" {{')
            lines.append(f'  let refused = try Ok(@dotenv.load("{escape(text)}")) catch {{')
            lines.append("    error => Err(error)")
            lines.append("  }")
            lines.append("  match refused {")
            lines.append("    Err(_) => ()")
            lines.append(f'    Ok(_) => fail("{type(error).__name__} should be refused")')
            lines.append("  }")
            lines.append("}")
            lines.append("")
            continue
        lines.append("///|")
        lines.append(f'test "python-dotenv: {label}" {{')
        lines.append(f'  let text = "{escape(text)}"')
        lines.append("  let env = @dotenv.load(text)")
        for key, value in values.items():
            if value is None:
                lines.append(f'  assert_eq(env.get("{escape(key)}"), None)')
            else:
                lines.append(
                    f'  assert_eq(env.get("{escape(key)}"), Some("{escape(value)}"))'
                )
        # A name with no value sets nothing, so it is not in the map.
        assigned = sum(1 for value in values.values() if value is not None)
        lines.append(f"  assert_eq(env.length(), {assigned})")
        lines.append(
            "  assert_eq(@dotenv.parse(text).keys(), ["
            + ", ".join(f'"{escape(key)}"' for key in keys)
            + "])"
        )
        lines.append("}")
        lines.append("")
    for index, text in enumerate(VERBATIM_CASES):
        values, _ = read(text, False)
        lines.append("///|")
        lines.append(f'test "python-dotenv verbatim {index + 1}" {{')
        lines.append(f'  let env = @dotenv.load("{escape(text)}", knobs=@dotenv.verbatim)')
        for key, value in values.items():
            if value is None:
                lines.append(f'  assert_eq(env.get("{escape(key)}"), None)')
            else:
                lines.append(
                    f'  assert_eq(env.get("{escape(key)}"), Some("{escape(value)}"))'
                )
        lines.append("}")
        lines.append("")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {target} ({len(CASES)} cases, {len(VERBATIM_CASES)} verbatim)")


if __name__ == "__main__":
    main()
