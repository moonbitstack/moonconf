#!/usr/bin/env python3
"""Generate the expansion vectors from bash.

Every case below is evaluated twice by a real POSIX shell -- once with `set -u`
and once without -- and the answer is written into a MoonBit test. The two runs
are the two policies `strict` and `lenient`: a shell that refuses an unset
variable is a shell under `set -u`, and one that reads it as nothing is a shell
without it.

A shell that cannot answer at all is recorded as a refusal, and the test asserts
that `moonconf/expand` refuses the same text rather than inventing a value.

The text under test is pasted into a double-quoted `printf`, which is the position
in which a shell expands it. No case contains a double quote, because one would
end that position.

Run from the repository root: python scripts/vectors/expand.py
"""

import os
import shutil
import subprocess
import tempfile


def find_bash():
    """A real bash, not the WSL stub Windows keeps in System32."""
    for candidate in (
        shutil.which("bash"),
        r"C://Program Files//Git//bin//bash.exe",
        r"C://Program Files//Git//usr//bin//bash.exe",
    ):
        if candidate and os.path.exists(candidate) and "System32" not in candidate:
            return candidate
    raise SystemExit("no bash found")

CASES = [
    ("defined", {"A": "value"}, "pre ${A} post"),
    ("unquoted", {"A": "value"}, "pre $A post"),
    ("two variables", {"A": "one", "B": "two"}, "${A}-${B}"),
    ("unset default", {"B": "b"}, "${A:-fallback}"),
    ("unset empty default", {"A": "", "B": "b"}, "${A:-fallback}"),
    ("unset minus", {"B": "b"}, "${A-fallback}"),
    ("empty minus", {"A": "", "B": "b"}, "${A-fallback}"),
    ("defined ignores default", {"A": "set"}, "${A:-fallback}"),
    ("assign when unset", {"B": "b"}, "${A:=assigned}-${A}"),
    ("assign when empty", {"A": ""}, "${A:=assigned}-${A}"),
    ("assign when set", {"A": "set"}, "${A:=assigned}-${A}"),
    ("assign minus", {"B": "b"}, "${A=assigned}-${A}"),
    ("question when set", {"A": "set"}, "${A:?must be set}"),
    ("question when empty", {"A": ""}, "${A:?must be set}"),
    ("question when unset", {}, "${A:?must be set}"),
    ("question minus when empty", {"A": ""}, "${A?must be set}"),
    ("plus when set", {"A": "set"}, "${A:+yes}"),
    ("plus when empty", {"A": ""}, "${A:+yes}"),
    ("plus when unset", {}, "${A:+yes}"),
    ("plus minus when empty", {"A": ""}, "${A+yes}"),
    ("length", {"A": "hello"}, "${#A}"),
    ("length of empty", {"A": ""}, "${#A}"),
    ("nested default", {"B": "inner"}, "${A:-${B}}"),
    ("nested with text", {"B": "inner"}, "${A:-x${B}y}"),
    ("nested unset", {"B": "inner"}, "${A:-${C:-deep}}"),
    ("escaped dollar", {"A": "value"}, "\\${A}"),
    ("escaped backslash then reference", {"A": "value"}, "\\\\${A}"),
    ("dollar alone", {}, "cost: $"),
    ("dollar before space", {"A": "v"}, "$ {A}"),
    ("more than a name", {"A": "v"}, "${A}x$Ay"),
    ("empty value stays empty", {"A": ""}, "[${A}]"),
    ("colon without operator", {"A": "v"}, "${A:}"),
]


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def shell_quote(text):
    return "'" + text.replace("'", "'\\''") + "'"


def run(text, env, strict):
    script = "set -u\n" if strict else ""
    for name, value in env.items():
        script += f"{name}={shell_quote(value)}\n"
    script += 'printf %s "' + text + '"\n'
    # Through a file, not through `-c`: the Windows runtime eats one level of
    # backslash in an argument, and half these cases are about backslashes.
    with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False, encoding="utf-8", newline="\n") as handle:
        handle.write(script)
        path = handle.name
    try:
        done = subprocess.run(
            [find_bash(), "--noprofile", "--norc", path],
            capture_output=True,
        )
    finally:
        os.unlink(path)
    if done.returncode != 0:
        return None
    return done.stdout.decode("utf-8", errors="replace")


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    target = os.path.join(root, "src", "expand", "vectors_test.mbt")
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/vectors/expand.py from bash. Do not edit by hand:",
        "// the answers below are what a real shell printed, which is the whole point.",
        "",
        "///|",
        "fn vars(pairs : Array[(String, String)]) -> @expand.Vars {",
        "  @expand.Vars::of_map(Map(pairs))",
        "}",
        "",
    ]
    for label, env, text in CASES:
        for strict in (True, False):
            answer = run(text, env, strict)
            policy = "@expand.strict" if strict else "@expand.lenient"
            pairs = ", ".join(f'("{k}", "{escape(v)}")' for k, v in env.items())
            name = f"bash{' -u' if strict else ''}: {label}"
            lines.append("///|")
            lines.append(f'test "{name}" {{')
            lines.append(f"  let vars = vars([{pairs}])")
            if answer is None:
                lines.append(
                    f'  let refused = try Ok(@expand.expand("{escape(text)}", vars, knobs={policy}))'
                    " catch { error => Err(error) }"
                )
                lines.append("  match refused {")
                lines.append("    Err(_) => ()")
                lines.append('    Ok(got) => fail("bash refused this text, expand answered " + got)')
                lines.append("  }")
            else:
                lines.append(
                    f'  assert_eq(@expand.expand("{escape(text)}", vars, knobs={policy}), "{escape(answer)}")'
                )
            lines.append("}")
            lines.append("")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {target} ({len(CASES) * 2} cases)")


if __name__ == "__main__":
    main()
